#!/usr/bin/env bash
# Prints the Homebrew formula for a release, from its checksums.txt.
# The release workflow attaches it to the release as askmywa.rb, and the
# abonur/homebrew-tap repository copies it from there.
#
# Usage: scripts/homebrew-formula.sh VERSION CHECKSUMS [DOWNLOAD_BASE]
#   DOWNLOAD_BASE defaults to https://github.com/abonur/askmywa/releases/download/vVERSION
set -euo pipefail

version="${1:?version}"
version="${version#v}"
sums="${2:?checksums.txt}"
base="${3:-https://github.com/abonur/askmywa/releases/download/v$version}"

sha() {
  local f="askmywa-$version-$1.tar.gz" s
  s=$(awk -v f="$f" '{ n = $2; sub(/^\.\//, "", n); sub(/^\*/, "", n); if (n == f) print $1 }' "$sums")
  if [[ ! $s =~ ^[0-9a-f]{64}$ ]]; then
    echo "error: no checksum for $f in $sums" >&2
    exit 1
  fi
  echo "$s"
}

block() {
  printf '      url "%s/askmywa-%s-%s.tar.gz"\n      sha256 "%s"\n' "$base" "$version" "$1" "$(sha "$1")"
}

cat <<EOF
# Generated by whatsapp-go/scripts/homebrew-formula.sh in abonur/askmywa.
class Askmywa < Formula
  desc "WhatsApp archive and MCP server for Claude and other AI assistants"
  homepage "https://github.com/abonur/askmywa"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
$(block darwin-arm64)
    end
    on_intel do
$(block darwin-amd64)
    end
  end

  on_linux do
    on_arm do
$(block linux-arm64)
    end
    on_intel do
$(block linux-amd64)
    end
  end

  def install
    if OS.mac?
      # askmywa.app gives the background service its name and logo in
      # System Settings; the command is a link to the binary inside it.
      libexec.install "askmywa.app"
      bin.install_symlink libexec/"askmywa.app/Contents/MacOS/askmywa"
    else
      bin.install "askmywa"
    end
  end

  def caveats
    <<~EOS
      Start the background service, then link your WhatsApp account:
        askmywa install-service
        askmywa link

      After \`brew upgrade askmywa\`, run \`askmywa install-service\`
      again to restart the service on the new version.

      MCP clients such as Claude Desktop run:
        #{opt_bin}/askmywa serve
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/askmywa version")
  end
end
EOF
